class Aut64Key:
    __slots__ = ("index", "key", "pbox", "sbox")

    def __init__(self):
        self.index = 0
        self.key = [0] * 8
        self.pbox = [0] * 8
        self.sbox = [0] * 16


def unpack(src):
    """src = 16 packed bytes -> Aut64Key."""
    k = Aut64Key()
    k.index = src[0]
    for i in range(4):
        k.key[i * 2] = src[i + 1] >> 4
        k.key[i * 2 + 1] = src[i + 1] & 0xF
    pbox = (src[5] << 16) | (src[6] << 8) | src[7]
    for i in range(7, -1, -1):
        k.pbox[i] = pbox & 0x7
        pbox >>= 3
    for i in range(8):
        k.sbox[i * 2] = src[i + 8] >> 4
        k.sbox[i * 2 + 1] = src[i + 8] & 0xF
    return k


def _key_nibble(k, nibble, table, it):
    kv = k.key[table[it]]
    return table_offset[((kv << 4) | nibble) & 0xFF]


def _round_key(k, state, rn):
    hi = lo = 0
    for i in range(BLOCK - 1):
        hi ^= _key_nibble(k, state[i] >> 4, table_un[rn], i)
        lo ^= _key_nibble(k, state[i] & 0x0F, table_ln[rn], i)
    return ((hi << 4) | lo) & 0xFF


def _final_byte_nibble(k, table):
    return (table_sub[k.key[table[BLOCK - 1]]] << 4) & 0xFF


def _dec_final_byte_nibble(k, nibble, table, result):
    off = _final_byte_nibble(k, table)
    return table_offset[((result ^ nibble) + off) & 0xFF]


def _decrypt_compress(k, state, rn):
    rk = _round_key(k, state, rn)
    hi = rk >> 4
    lo = rk & 0x0F
    hi = _dec_final_byte_nibble(k, state[BLOCK - 1] >> 4, table_un[rn], hi)
    lo = _dec_final_byte_nibble(k, state[BLOCK - 1] & 0x0F, table_ln[rn], lo)
    return ((hi << 4) | lo) & 0xFF


def _substitute(k, b):
    return ((k.sbox[b >> 4] << 4) | k.sbox[b & 0x0F]) & 0xFF


def _permute_bits(k, b):
    r = 0
    for i in range(8):
        if b & (1 << i):
            r |= 1 << k.pbox[i]
    return r & 0xFF


def _permute_bytes(k, state):
    res = [0] * BLOCK
    for i in range(BLOCK):
        res[k.pbox[i]] = state[i]
    state[:] = res


def decrypt(k, msg):
    """Decrypt 8-byte msg (list) in place."""
    for i in range(NUM_ROUNDS - 1, -1, -1):
        msg[7] = _substitute(k, msg[7])
        msg[7] = _permute_bits(k, msg[7])
        msg[7] = _substitute(k, msg[7])
        msg[7] = _decrypt_compress(k, msg, i)
        _permute_bytes(k, msg)
    return msg

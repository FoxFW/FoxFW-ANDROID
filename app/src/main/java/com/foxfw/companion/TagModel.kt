package com.foxfw.companion

/**
 * Tag model for the Tag Maker. A [Tag] serializes to the Flipper `.nfc` / `.rfid`
 * text formats (so `fox_nfc_io.fap` and the Chameleon backend can consume it) and
 * parses back from them (for clone-from-read and library import).
 *
 * Formats verified against the firmware serializers:
 *   .nfc   : "Filetype: Flipper NFC device" / Version 4 / "Device type: <name>" /
 *            "UID: XX .." (+ "ATQA"/"SAK" for 14443-3A, "Mifare Classic type" +
 *            "Block N: .." for MFC, "Page N: .." for Ultralight/NTAG).
 *   .rfid  : "Filetype: Flipper RFID key" / Version 1 / "Key type: <EM4100|HIDProx..>" /
 *            "Data: XX .."  (EM4100 = 5 bytes).
 */

enum class TagClass { HF, LF }

enum class TagType(val cls: TagClass, val label: String) {
    // LF
    EM4100(TagClass.LF, "EM4100"),
    HID_PROX(TagClass.LF, "HID Prox (H10301)"),
    // HF
    MIFARE_CLASSIC_1K(TagClass.HF, "MIFARE Classic 1K"),
    MIFARE_CLASSIC_4K(TagClass.HF, "MIFARE Classic 4K"),
    MIFARE_ULTRALIGHT(TagClass.HF, "MIFARE Ultralight"),
    NTAG213(TagClass.HF, "NTAG213"),
    NTAG215(TagClass.HF, "NTAG215"),
    NTAG216(TagClass.HF, "NTAG216"),
    ISO14443_3A(TagClass.HF, "ISO14443-3A (UID)"),
}

private fun hex(b: ByteArray) = b.joinToString(" ") { "%02X".format(it) }
private fun unhex(s: String): ByteArray =
    s.trim().split(Regex("\\s+")).filter { it.isNotEmpty() }.map { it.toInt(16).toByte() }.toByteArray()

sealed class Tag {
    abstract val type: TagType
    abstract fun toFlipperFile(): String
    /** Compact payload the Chameleon backend uploads into a slot (impl detail of that backend). */
    abstract fun chameleonUid(): ByteArray
}

/** NTAG/Ultralight use 4-byte pages; MFC uses 16-byte blocks; 14443-3A is UID only. */
data class HfTag(
    override val type: TagType,
    val uid: ByteArray,
    val atqa: ByteArray = byteArrayOf(0x00, 0x44),
    val sak: Int = 0x00,
    val blocks: List<ByteArray> = emptyList(), // MFC 16-byte blocks OR NTAG 4-byte pages
    val mfcTypeName: String = "",               // "1K"/"4K" for MFC device-type line
) : Tag() {
    override fun chameleonUid() = uid

    private fun ntagSubtypeName(): String = when (type) {
        TagType.NTAG213 -> "NTAG213"
        TagType.NTAG215 -> "NTAG215"
        TagType.NTAG216 -> "NTAG216"
        else -> "Mifare Ultralight"
    }
    // GET_VERSION response bytes per NTAG subtype (used by the Flipper loader).
    private fun ntagVersion(): ByteArray = when (type) {
        TagType.NTAG213 -> byteArrayOf(0x00, 0x04, 0x04, 0x02, 0x01, 0x00, 0x0F, 0x03)
        TagType.NTAG215 -> byteArrayOf(0x00, 0x04, 0x04, 0x02, 0x01, 0x00, 0x11, 0x03)
        TagType.NTAG216 -> byteArrayOf(0x00, 0x04, 0x04, 0x02, 0x01, 0x00, 0x13, 0x03)
        else -> byteArrayOf(0x00, 0x04, 0x03, 0x01, 0x01, 0x00, 0x0B, 0x03)
    }

    private fun deviceTypeName(): String = when (type) {
        TagType.MIFARE_CLASSIC_1K, TagType.MIFARE_CLASSIC_4K -> "Mifare Classic"
        TagType.MIFARE_ULTRALIGHT, TagType.NTAG213, TagType.NTAG215, TagType.NTAG216 -> "NTAG/Ultralight"
        TagType.ISO14443_3A -> "ISO14443-3A"
        else -> "ISO14443-3A"
    }

    override fun toFlipperFile(): String = buildString {
        appendLine("Filetype: Flipper NFC device")
        appendLine("Version: 4")
        appendLine("# Generated by FoxFW companion Tag Maker")
        appendLine("Device type: ${deviceTypeName()}")
        appendLine("# UID is common for all formats")
        appendLine("UID: ${hex(uid)}")
        appendLine("ATQA: ${hex(atqa)}")
        appendLine("SAK: %02X".format(sak))
        when (type) {
            TagType.MIFARE_CLASSIC_1K, TagType.MIFARE_CLASSIC_4K -> {
                appendLine("# Mifare Classic specific data")
                appendLine("Mifare Classic type: ${if (type == TagType.MIFARE_CLASSIC_4K) "4K" else "1K"}")
                appendLine("Data format version: 2")
                blocks.forEachIndexed { i, b -> appendLine("Block $i: ${hex(b)}") }
            }
            TagType.MIFARE_ULTRALIGHT, TagType.NTAG213, TagType.NTAG215, TagType.NTAG216 -> {
                appendLine("# NTAG/Ultralight specific data")
                appendLine("Data format version: 2")
                appendLine("NTAG/Ultralight type: ${ntagSubtypeName()}")
                appendLine("Signature: ${hex(ByteArray(32))}")
                appendLine("Mifare version: ${hex(ntagVersion())}")
                for (c in 0..2) { appendLine("Counter $c: 0"); appendLine("Tearing $c: 00") }
                appendLine("Pages total: ${blocks.size}")
                appendLine("Pages read: ${blocks.size}")
                blocks.forEachIndexed { i, b -> appendLine("Page $i: ${hex(b)}") }
            }
            else -> {}
        }
    }

    override fun equals(other: Any?) = other is HfTag && type == other.type && uid.contentEquals(other.uid) &&
        blocks.size == other.blocks.size && blocks.zip(other.blocks).all { (a, b) -> a.contentEquals(b) }
    override fun hashCode() = type.hashCode() * 31 + uid.contentHashCode()
}

/** LF key: EM4100 = 5 data bytes; HID H10301 = facility/card packed to the Flipper Data bytes. */
data class LfTag(
    override val type: TagType,
    val data: ByteArray,
    /** Explicit lfrfid key-type name (set when cloned from a read); else derived from [type]. */
    val keyType: String? = null,
) : Tag() {
    override fun chameleonUid() = data

    fun keyTypeName(): String = keyType ?: when (type) {
        TagType.EM4100 -> "EM4100"
        TagType.HID_PROX -> "H10301"
        else -> "EM4100"
    }

    override fun toFlipperFile(): String = buildString {
        appendLine("Filetype: Flipper RFID key")
        appendLine("Version: 1")
        appendLine("# Generated by FoxFW companion Tag Maker")
        appendLine("Key type: ${keyTypeName()}")
        appendLine("Data: ${hex(data)}")
    }

    companion object {
        /** EM4100 from a 5-byte ID (10 hex chars). */
        fun em4100(idHex: String): LfTag = LfTag(TagType.EM4100, unhex(idHex).also {
            require(it.size == 5) { "EM4100 ID must be 5 bytes (10 hex)" }
        })

        /**
         * HID H10301 26-bit from facility (0..255) + card (0..65535). The lfrfid .rfid
         * "Data" for H10301 is the 3-byte DECODED value [facility, card>>8, card&0xFF]
         * (protocol_h10301.c: fc_cn = data[0]<<16 | data[1]<<8 | data[2]); the engine
         * adds the FSK/Wiegand parity encoding on emulate/write.
         */
        fun hidH10301(facility: Int, card: Int): LfTag {
            require(facility in 0..255) { "HID facility 0..255" }
            require(card in 0..65535) { "HID card 0..65535" }
            return LfTag(
                TagType.HID_PROX,
                byteArrayOf(facility.toByte(), ((card ushr 8) and 0xFF).toByte(), (card and 0xFF).toByte()),
                keyType = "H10301",
            )
        }
    }

    override fun equals(other: Any?) = other is LfTag && type == other.type && data.contentEquals(other.data)
    override fun hashCode() = type.hashCode() * 31 + data.contentHashCode()
}

object TagCodec {
    /** Parse a Flipper .nfc / .rfid file. Returns null if unrecognized. */
    fun parseFlipperFile(text: String): Tag? {
        val lines = text.lineSequence().map { it.trim() }.filter { it.isNotEmpty() && !it.startsWith("#") }.toList()
        fun field(key: String) = lines.firstOrNull { it.startsWith("$key:") }?.substringAfter(":")?.trim()
        val filetype = field("Filetype") ?: return null
        return if (filetype.contains("RFID")) {
            val kt = field("Key type") ?: return null
            val data = field("Data")?.let { unhex(it) } ?: return null
            val t = when (kt) { "H10301", "HIDProx" -> TagType.HID_PROX; "EM4100" -> TagType.EM4100; else -> TagType.EM4100 }
            // keyType carries the exact lfrfid name so a cloned non-EM protocol re-emulates/writes correctly.
            LfTag(t, data, keyType = kt)
        } else if (filetype.contains("NFC device")) {
            val dev = field("Device type") ?: return null
            val uid = field("UID")?.let { unhex(it) } ?: return null
            val atqa = field("ATQA")?.let { unhex(it) } ?: byteArrayOf(0, 0x44)
            val sak = field("SAK")?.let { it.trim().toInt(16) } ?: 0
            val mfcType = field("Mifare Classic type")
            val ulType = field("NTAG/Ultralight type")
            val type = when {
                dev.contains("Mifare Classic") -> if (mfcType == "4K") TagType.MIFARE_CLASSIC_4K else TagType.MIFARE_CLASSIC_1K
                dev.contains("NTAG") || dev.contains("Ultralight") -> when (ulType) {
                    "NTAG213" -> TagType.NTAG213
                    "NTAG215" -> TagType.NTAG215
                    "NTAG216" -> TagType.NTAG216
                    else -> TagType.MIFARE_ULTRALIGHT
                }
                else -> TagType.ISO14443_3A
            }
            val blocks = lines.filter { it.matches(Regex("(Block|Page) \\d+:.*")) }
                .map { unhex(it.substringAfter(":")) }
            HfTag(type, uid, atqa, sak, blocks, mfcType ?: "")
        } else null
    }
}
